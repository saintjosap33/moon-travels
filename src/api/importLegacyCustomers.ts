export default createEndpoint({
  description: 'Import legacy customers from MySQL dump - safe, idempotent migration',
  inputSchema: z.object({}),
  outputSchema: z.object({
    totalRowsParsed: z.number(),
    successfullyImported: z.number(),
    skipped: z.number(),
    duplicateConflicts: z.number(),
    invalidRecords: z.number(),
    skippedReasons: z.array(z.object({
      legacyId: z.number(),
      email: z.string(),
      reason: z.string(),
    })),
    existingCustomerCountBefore: z.number(),
    finalCustomerCount: z.number(),
    recordsWithNullPhone: z.number(),
    recordsWithNonNullPhone: z.number(),
    migrationStrategy: z.string(),
    idempotencyNote: z.string(),
  }),
  execute: async () => {
    // Step 1: Get existing customers to check for conflicts
    const existingResult = await zite.customers.findAll({ limit: 2000 });
    const existingEmails = new Set(existingResult.records.map(c => c.email));
    const existingCustomerCountBefore = existingResult.records.length;

    // Step 2: Parse and validate legacy records
    const skippedReasons: Array<{ legacyId: number; email: string; reason: string }> = [];
    let duplicateConflicts = 0;
    let invalidRecords = 0;
    let recordsWithNullPhone = 0;
    let recordsWithNonNullPhone = 0;

    // Step 3: Transform legacy records into current schema
    const recordsToImport: CustomersRecordInput[] = [];

    for (const legacyRecord of legacyCustomers) {
      // Validate required fields
      if (!legacyRecord.email || !legacyRecord.name) {
        invalidRecords++;
        skippedReasons.push({
          legacyId: legacyRecord.customer_id,
          email: legacyRecord.email || 'MISSING',
          reason: 'Missing required field (email or name)',
        });
        continue;
      }

      // Check for duplicate email
      if (existingEmails.has(legacyRecord.email)) {
        duplicateConflicts++;
        skippedReasons.push({
          legacyId: legacyRecord.customer_id,
          email: legacyRecord.email,
          reason: 'Email already exists in current database',
        });
        continue;
      }

      // Track phone nullability
      if (legacyRecord.phone === null) {
        recordsWithNullPhone++;
      } else {
        recordsWithNonNullPhone++;
      }

      // Split name into firstName/lastName
      const nameParts = legacyRecord.name.trim().split(' ');
      const firstName = nameParts[0] || legacyRecord.name;
      const lastName = nameParts.length > 1 ? nameParts.slice(1).join(' ') : '';

      recordsToImport.push({
        firstName,
        lastName: lastName || firstName, // Use firstName if no lastName
        email: legacyRecord.email,
        phone: legacyRecord.phone || null,
        // Other fields default to null per current schema
        address: null,
        city: null,
        state: null,
        postalCode: null,
        dateOfBirth: null,
        customerRating: null,
        bookings: null,
        reviews: null,
      });

      // Add email to existing set to prevent duplicates within this batch
      existingEmails.add(legacyRecord.email);
    }

    // Step 4: Import in batches (max 100 per call)
    let successfullyImported = 0;
    const batchSize = 100;

    for (let i = 0; i < recordsToImport.length; i += batchSize) {
      const batch = recordsToImport.slice(i, i + batchSize);
      try {
        const result = await zite.customers.bulkCreate({
          records: batch,
        });
        successfullyImported += result.records.length;
      } catch (error) {
        console.error(`Error importing batch ${i / batchSize + 1}:`, error);
        throw error;
      }
    }

    // Step 5: Verify final count
    const finalResult = await zite.customers.findAll({ limit: 2000 });
    const finalCustomerCount = finalResult.records.length;

    return {
      totalRowsParsed: legacyCustomers.length,
      successfullyImported,
      skipped: duplicateConflicts + invalidRecords,
      duplicateConflicts,
      invalidRecords,
      skippedReasons,
      existingCustomerCountBefore,
      finalCustomerCount,
      recordsWithNullPhone,
      recordsWithNonNullPhone,
      migrationStrategy: 'Legacy MySQL ID → UUID mapping via email uniqueness. Names split into firstName/lastName. All optional fields set to null. Idempotent via email constraint.',
      idempotencyNote: 'Safe to run again - duplicate emails are detected and skipped. Existing customers never overwritten.',
    };
  },
});
